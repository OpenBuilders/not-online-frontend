/** Every land cell as [col, row]. Computed once on import. */
export const LAND_CELLS: [number, number][] = (() => {
  const cells: [number, number][] = [];
  WORLD.hex.forEach((row, r) => {
    for (let i = 0; i < row.length; i++) {
      const nibble = parseInt(row[i], 16);
      for (let b = 0; b < 4; b++) {
        const c = i * 4 + b;
        if (c < WORLD.cols && nibble & (8 >> b)) cells.push([c, r]);
      }
    }
  });
  return cells;
})();

